"""The reconnaissance scripts must match a version whose hash is recorded as evidence.

Each summary in docs/sources/ records the SHA-256 of the script that produced it.
Changing a script without producing new evidence breaks that link, so this test
fails until a summary generated by the new version is versioned.

The scripts hash the file as it is on disk, and Git on Windows (core.autocrlf) can
check it out with CRLF: the same commit then gives a different hash (for example
inspector_sha256 in the 2021 and 2025 summaries). The comparison therefore uses
LF line endings, the form stored in the repository.
"""

import hashlib
import json
from pathlib import Path

import pytest


SOURCES_DIR = Path(__file__).resolve().parents[2] / "docs" / "sources"
SCRIPTS_DIR = Path(__file__).resolve().parents[2] / "scripts"


def recorded_hashes(field):
    hashes = set()
    for path in SOURCES_DIR.glob("*.json"):
        value = json.loads(path.read_text(encoding="utf-8")).get(field)
        if value is not None:
            hashes.add(value)
    return hashes


@pytest.mark.parametrize(
    ("script", "field"),
    [("inspect_sercop_zip.py", "inspector_sha256"), ("profile_sercop_fields.py", "profiler_sha256")],
)
def test_script_matches_a_recorded_version(script, field):
    content = (SCRIPTS_DIR / script).read_bytes().replace(b"\r\n", b"\n")
    recorded = recorded_hashes(field)

    assert recorded, f"No summary in docs/sources/ records {field}"
    assert hashlib.sha256(content).hexdigest().upper() in recorded
